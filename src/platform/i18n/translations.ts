/**
 * Complete dictionary map keyed by `SupportedLocale`.
 */
export const TRANSLATIONS: Record<SupportedLocale, TranslationDictionary> = {
  en,
  it,
  es,
};

/**
 * Interpolates `{key}` placeholders in a translation string for the requested locale.
 * @param {SupportedLocale} locale - Active UI locale.
 * @param {TranslationKey} key - Strictly typed translation key.
 * @param {Record<string, string | number>} [params] - Optional placeholder replacements.
 * @returns {string} Localized formatted string.
 */
export function translate(
  locale: SupportedLocale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const dict = TRANSLATIONS[locale] ?? en;
  let value = dict[key];
  if (params) {
    for (const [paramKey, paramValue] of Object.entries(params)) {
      value = value.replaceAll(`{${paramKey}}`, String(paramValue));
    }
  }
  return value;
}
